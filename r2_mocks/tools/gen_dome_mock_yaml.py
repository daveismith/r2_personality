"""
Generate ``config/dome_mock.yaml`` from the captured ``ListLeds`` and ``ListMagicPanel`` output.

    python3 tools/gen_dome_mock_yaml.py LEDS.txt MAGIC.txt > config/dome_mock.yaml

The inputs are the raw ``ros2 service call`` outputs saved in ``r2_personality/docs/dome/``;
their last line is the Python repr of the response, which is evaluated against the real
``astromech_msgs`` classes (so run it with the workspace sourced). A droid's own capture
replaces the workbench one by running this on it.
"""

import sys

import astromech_msgs.msg
import astromech_msgs.srv
import yaml

DISPLAY_FIELDS = ('name', 'display', 'kind', 'rows', 'cols', 'leds', 'has_text', 'has_drift')
SURFACE_FIELDS = ('name', 'display', 'displays', 'width', 'height', 'clip_target')
CLIP_FIELDS = ('name', 'target', 'frames', 'length_ms', 'loops', 'tintable', 'source')
DESCRIPTOR_FIELDS = (
    'link', 'unsupported', 'fw_major', 'fw_minor', 'fw_patch', 'proto_major', 'proto_minor',
    'seq_count', 'cached', 'has_legacy', 'has_repeat', 'has_brightness', 'has_names',
    'has_eeprom_config', 'has_orientation', 'address', 'scl_hz', 'poll_period_ms')
SEQUENCE_FIELDS = ('id', 'name', 'flags', 'length_ms')


def parse_response(path):
    """Return the response object printed on the ``astromech_msgs.srv.*_Response(`` line."""
    with open(path) as handle:
        for line in handle:
            if line.startswith('astromech_msgs.srv.') and '_Response(' in line:
                return eval(line, {'astromech_msgs': astromech_msgs})     # noqa: S307
    raise SystemExit('%s: no response line found' % path)


def fields(msg, names):
    """Return the named fields of a message as a plain dict."""
    out = {}
    for name in names:
        value = getattr(msg, name)
        out[name] = list(value) if isinstance(value, list) else value
    return out


def build(leds_path, magic_path):
    """Return the catalogue dict for the two captures."""
    leds = parse_response(leds_path)
    magic = parse_response(magic_path)
    return {
        'displays': [fields(d, DISPLAY_FIELDS) for d in leds.displays],
        'surfaces': [fields(s, SURFACE_FIELDS) for s in leds.surfaces],
        'effects': [{'name': n, 'summary': s}
                    for n, s in zip(leds.effects, leds.effect_summaries)],
        'clips': [fields(c, CLIP_FIELDS) for c in leds.clips],
        'text_motions': list(leds.text_motions),
        'drift_presets': list(leds.drift_presets),
        'magic': {
            'panel': fields(magic.panel, DESCRIPTOR_FIELDS),
            'sequences': [fields(s, SEQUENCE_FIELDS) for s in magic.sequences],
        },
    }


def main(argv=None):
    """Print the YAML for the two capture files named on the command line."""
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 2:
        raise SystemExit(__doc__)
    text = yaml.safe_dump(build(*argv), sort_keys=False, width=100)
    sys.stdout.write('# Generated by tools/gen_dome_mock_yaml.py from the workbench captures in\n'
                     '# r2_personality/docs/dome/ (2026-10-20). Do not edit; regenerate.\n')
    sys.stdout.write(text)


if __name__ == '__main__':
    main()
